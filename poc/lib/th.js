/** Thai name/theme/meaning for a deck card (major or minor). */
export function tarotThai(card) {
  if (card.arcana === 'major') {
    const [name, theme, meaning] = MAJOR_TH[card.id];
    return { nameTh: name, themeTh: theme, meaningTh: `${meaning}` };
  }
  const rankId = card.id.split('-of-')[0];
  const suit = SUIT_TH[card.suit];
  const [rankName, rankTheme, rankMeaning] = RANK_TH[rankId];
  return {
    nameTh: `${rankName}${suit.name} (${card.name})`,
    themeTh: `${rankTheme} · ${suit.theme}`,
    meaningTh: `${rankMeaning} ในด้าน${suit.domain} ลองพิจารณาว่า${suit.nudge}จะช่วยได้หรือไม่`
  };
}

